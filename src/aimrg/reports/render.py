"""Render governance documents from recorded evidence.

Templates are Jinja2 files in a pack's ``templates/`` directory and produce Markdown.
Markdown can be converted to Word with :func:`aimrg.reports.docx.markdown_to_docx`.

Templates draw only on recorded facts. Narrative judgments (conclusions, conditions of
use) are left as clearly marked placeholders for a human to complete; generated
documents never assert compliance.
"""

from __future__ import annotations

import json
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, StrictUndefined, TemplateNotFound

from aimrg import __version__
from aimrg.core.models import EvidenceType, FindingStatus
from aimrg.packs.resolver import CoverageStatus, ResolverError, coverage
from aimrg.registry.store import Registry, RegistryError

DISCLAIMER = (
    "Generated by AI-MRG from recorded evidence. Sections marked [TO COMPLETE] require "
    "human judgment. This document does not by itself establish regulatory compliance "
    "and is not legal advice."
)

ASSET_TEMPLATES = ("validation_report",)
PORTFOLIO_TEMPLATES = ("inventory_report",)


def _cell(value: Any) -> str:
    """Make a value safe inside a Markdown table cell."""
    if value is None:
        return "—"
    text = str(value).replace("|", "\\|").replace("\n", " ").strip()
    return text or "—"


def _pct(value: Any, digits: int = 1) -> str:
    return "—" if value is None else f"{float(value):.{digits}%}"


def _num(value: Any, digits: int = 3) -> str:
    if value is None:
        return "—"
    if isinstance(value, int):
        return str(value)
    try:
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def _environment(registry: Registry) -> Environment:
    templates = registry.pack.templates_dir
    if templates is None or not Path(templates).is_dir():
        raise RegistryError(f"pack {registry.pack.manifest.ref} has no templates directory")
    env = Environment(
        loader=FileSystemLoader(templates),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
        autoescape=False,  # noqa: S701 - output is Markdown, not HTML
    )
    env.filters.update(cell=_cell, pct=_pct, num=_num)
    return env


def available_templates(registry: Registry) -> list[str]:
    templates = registry.pack.templates_dir
    if templates is None or not Path(templates).is_dir():
        return []
    return sorted(p.name.removesuffix(".md.j2") for p in Path(templates).glob("*.md.j2"))


def _base_context(registry: Registry) -> dict[str, Any]:
    return {
        "generated_at": datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "aimrg_version": __version__,
        "pack": registry.pack.manifest,
        "disclaimer": DISCLAIMER,
    }


def asset_context(registry: Registry, ref: str) -> dict[str, Any]:
    asset = registry.get(ref)
    evidence = registry.evidence(asset.id)
    try:
        cov = coverage(registry.pack, asset, evidence)
    except ResolverError as exc:
        raise RegistryError(f"cannot report on {asset.name!r}: {exc}") from exc

    check_results = []
    for item in evidence:
        if item.type is EvidenceType.CHECK_RESULT and item.payload_uri:
            payload = json.loads(registry.read_artifact(item.payload_uri))
            check_results.append({"evidence": item, **payload["result"]})

    profile = None
    if asset.risk_assessment:
        profile_id = asset.risk_assessment.profile_id.split("/")[-1]
        try:
            profile = registry.pack.tiering_profile(profile_id)
        except KeyError:
            profile = None

    findings = registry.findings(asset.id)
    status_counts = Counter(c.status.value for c in cov)
    return {
        **_base_context(registry),
        "asset": asset,
        "upstream": [registry.get(d) for d in asset.depends_on],
        "downstream": registry.dependents(asset.id),
        "profile": profile,
        "coverage": cov,
        "coverage_counts": {s.value: status_counts.get(s.value, 0) for s in CoverageStatus},
        "evidence": evidence,
        "check_results": check_results,
        "findings": findings,
        "open_findings": [
            f
            for f in findings
            if f.status not in (FindingStatus.CLOSED, FindingStatus.RISK_ACCEPTED)
        ],
    }


def portfolio_context(registry: Registry) -> dict[str, Any]:
    rows = []
    for asset in registry.assets():
        findings = registry.findings(asset.id)
        open_count = sum(
            f.status not in (FindingStatus.CLOSED, FindingStatus.RISK_ACCEPTED) for f in findings
        )
        try:
            cov = coverage(registry.pack, asset, registry.evidence(asset.id))
            complete = sum(c.status is CoverageStatus.COMPLETE for c in cov)
            required = len(cov)
        except ResolverError:
            complete, required = None, None
        rows.append(
            {
                "asset": asset,
                "track": asset.classification.track.value if asset.classification else None,
                "tier": asset.risk_assessment.tier if asset.risk_assessment else None,
                "open_findings": open_count,
                "controls_complete": complete,
                "controls_required": required,
            }
        )
    by_tier = Counter(r["tier"] for r in rows if r["tier"] is not None)
    by_track = Counter(r["track"] for r in rows if r["track"] is not None)
    return {
        **_base_context(registry),
        "rows": rows,
        "by_tier": dict(sorted(by_tier.items())),
        "by_track": dict(sorted(by_track.items())),
        "unclassified": [r["asset"] for r in rows if r["track"] is None],
        "untiered": [r["asset"] for r in rows if r["track"] is not None and r["tier"] is None],
    }


def render(registry: Registry, template: str, asset_ref: str | None = None) -> str:
    """Render ``template`` (e.g. ``validation_report``) to Markdown."""
    env = _environment(registry)
    try:
        tpl = env.get_template(f"{template}.md.j2")
    except TemplateNotFound as exc:
        raise RegistryError(
            f"no template {template!r}; available: {available_templates(registry)}"
        ) from exc
    if template in PORTFOLIO_TEMPLATES:
        context = portfolio_context(registry)
    else:
        if asset_ref is None:
            raise RegistryError(f"template {template!r} needs an asset")
        context = asset_context(registry, asset_ref)
    return tpl.render(**context)
